// Rewrites src/games/registry.ts from the game folders that exist, in shelf order.
// Run after merging game lanes: node scripts/gen-registry.mjs
import { existsSync, writeFileSync } from 'node:fs'
const ORDER = ['phases', 'aggro', 'percent', 'board', 'kart', 'survive', 'trivia', 'quip', 'bluff', 'fakeword', 'sketch', 'drawbluff', 'telephone', 'melon', 'categories', 'forehead', 'bowl', 'arena']
const ids = ORDER.filter((id) => existsSync(`src/games/${id}/index.ts`))
const name = (id) => id.replace(/-(\w)/g, (_, c) => c.toUpperCase())
const out = `import type { GameDef } from '../engine/types'
${ids.map((id) => `import ${name(id)} from './${id}'`).join('\n')}

/** Every playable game, in shelf order. Each game lives in its own folder under src/games/. Generated by scripts/gen-registry.mjs. */
export const GAMES: GameDef[] = [${ids.map(name).join(', ')}]

export function getGame(id: string): GameDef | null {
  return GAMES.find((g) => g.id === id) ?? null
}
`
writeFileSync('src/games/registry.ts', out)
console.log('registry:', ids.join(', '))
