import type { GameDef } from '../engine/types'
import phases from './phases'
import aggro from './aggro'
import percent from './percent'
import board from './board'
import kart from './kart'
import survive from './survive'
import trivia from './trivia'
import quip from './quip'
import bluff from './bluff'
import fakeword from './fakeword'
import sketch from './sketch'
import drawbluff from './drawbluff'
import telephone from './telephone'
import melon from './melon'
import categories from './categories'
import forehead from './forehead'
import bowl from './bowl'
import arena from './arena'

/** Every playable game, in shelf order. Each game lives in its own folder under src/games/. Generated by scripts/gen-registry.mjs. */
export const GAMES: GameDef[] = [phases, aggro, percent, board, kart, survive, trivia, quip, bluff, fakeword, sketch, drawbluff, telephone, melon, categories, forehead, bowl, arena]

export function getGame(id: string): GameDef | null {
  return GAMES.find((g) => g.id === id) ?? null
}
